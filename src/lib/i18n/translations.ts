const englishToTranslationKey = new Map<string, TranslationKey>();
(Object.keys(translations.en) as TranslationKey[]).forEach((key) => {
  englishToTranslationKey.set(translations.en[key], key);
});

export function translateText(language: Language, text: string): string {
  if (language === 'fr') {
    if (frenchText[text]) return frenchText[text];
    const key = englishToTranslationKey.get(text);
    if (key) return translations.fr[key];

    const dynamicTranslations: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
      [/^Club “(.+)” created\.$/, (match) => `Le club « ${match[1]} » a été créé.`],
      [/^You joined (.+)\.$/, (match) => `Vous avez rejoint ${match[1]}.`],
      [/^(.+) is already registered for (.+)\.$/, (match) => `${match[1]} est déjà inscrit à ${match[2]}.`],
      [/^An invitation for (.+) is already pending\.$/, (match) => `Une invitation pour ${match[1]} est déjà en attente.`],
      [/^Tournament invitation sent to (.+)\.$/, (match) => `Invitation au tournoi envoyée à ${match[1]}.`],
      [/^Messages with (.+)$/, (match) => `Messages avec ${match[1]}`],
      [/^Chat with (.+)$/, (match) => `Discussion avec ${match[1]}`],
    ];
    for (const [pattern, translate] of dynamicTranslations) {
      const match = text.match(pattern);
      if (match) return translate(match);
    }
    return text;
  }

  if (language === 'ar') {
    if (arabicText[text]) return arabicText[text];
    const dynamicTranslations: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
      [/^Club “(.+)” created\.$/, (match) => `تم إنشاء النادي «${match[1]}».`],
      [/^You joined (.+)\.$/, (match) => `انضممت إلى ${match[1]}.`],
      [/^(.+) is already registered for (.+)\.$/, (match) => `${match[1]} مسجل بالفعل في ${match[2]}.`],
      [/^An invitation for (.+) is already pending\.$/, (match) => `هناك دعوة معلقة بالفعل إلى ${match[1]}.`],
      [/^Tournament invitation sent to (.+)\.$/, (match) => `تم إرسال دعوة البطولة إلى ${match[1]}.`],
      [/^Messages with (.+)$/, (match) => `الرسائل مع ${match[1]}`],
      [/^Chat with (.+)$/, (match) => `محادثة مع ${match[1]}`],
    ];
    for (const [pattern, translate] of dynamicTranslations) {
      const match = text.match(pattern);
      if (match) return translate(match);
    }
    return text;
  }
  return text;
}
